package com.awakekt.releaseguard.gradle

/** Plain immutable snapshot of rule generation flags used by [ProGuardRuleGenerator]. */
public data class ProGuardRuleConfig(
    public val mainClass: String = "",
    public val repackageClasses: String = "",
    public val allowAccessModification: Boolean = true,
    public val overloadAggressively: Boolean = true,
    public val renameSourceFileAttribute: String = "SourceFile",
    public val stripKotlinIntrinsics: Boolean = true,
    public val stripKotlinMetadata: Boolean = false,
    public val stripAndroidLogs: Boolean = true,
    public val keepKotlinxSerialization: Boolean = true,
    public val keepEnums: Boolean = true,
    public val keepJnaLibraries: Boolean = true,
    public val keepComposeModifiers: Boolean = true,
    public val desktopDontOptimize: Boolean = true,
    public val extraRules: List<String> = emptyList(),
    public val extraDesktopRules: List<String> = emptyList(),
    public val extraAndroidRules: List<String> = emptyList(),
)

/**
 * Generates deterministic ProGuard (Desktop JVM) and R8 (Android) configuration files for KMP apps
 * and games.
 */
public object ProGuardRuleGenerator {
    /** Emits desktop ProGuard rules for shrinking and obfuscating JVM JARs. */
    public fun generateDesktopRules(config: ProGuardRuleConfig): String = buildString {
        appendLine("# Generated by com.awakekt.release-guard (desktop ProGuard rules). Do not edit.")
        appendCommonHardening(this, config)
        if (config.desktopDontOptimize) {
            appendLine()
            appendLine("# Disable ProGuard bytecode optimizer to avoid JVM stack-map VerifyErrors in long Kotlin methods.")
            appendLine("-dontoptimize")
        }
        if (config.mainClass.isNotBlank()) {
            appendLine()
            appendLine("# Desktop launcher entrypoint.")
            appendLine("-keep class ${config.mainClass.trim()} {")
            appendLine("    public static void main(java.lang.String[]);")
            appendLine("}")
        }
        if (config.keepJnaLibraries) {
            appendLine()
            appendLine("# Keep JNA native interface method names.")
            appendLine("-keep interface * extends com.sun.jna.Library { *; }")
        }
        appendSharedKeepRules(this, config, androidSignatures = false)
        appendExtraRules(this, config.extraRules + config.extraDesktopRules)
    }

    /** Emits Android R8 rules for release APK/AAB builds. */
    public fun generateAndroidRules(config: ProGuardRuleConfig): String = buildString {
        appendLine("# Generated by com.awakekt.release-guard (Android R8 rules). Do not edit.")
        appendCommonHardening(this, config)
        appendSharedKeepRules(this, config, androidSignatures = true)
        if (config.stripAndroidLogs) {
            appendLine()
            appendLine("# Strip verbose and debug Android Log calls in release builds.")
            appendLine("-assumenosideeffects class android.util.Log {")
            appendLine("    public static int v(...);")
            appendLine("    public static int d(...);")
            appendLine("}")
        }
        if (config.keepComposeModifiers) {
            appendLine()
            appendLine("# Prevent R8 horizontal class merging from folding distinct Compose ModifierNodeElement classes together.")
            appendLine("-keep,allowobfuscation,allowshrinking class * extends com.awakekt.awake.compose.ui.ModifierNodeElement")
        }
        appendExtraRules(this, config.extraRules + config.extraAndroidRules)
    }

    private fun appendCommonHardening(out: StringBuilder, config: ProGuardRuleConfig) {
        out.appendLine()
        out.appendLine("-repackageclasses '${config.repackageClasses}'")
        if (config.allowAccessModification) out.appendLine("-allowaccessmodification")
        if (config.overloadAggressively) out.appendLine("-overloadaggressively")
        if (config.renameSourceFileAttribute.isNotBlank()) {
            out.appendLine("-renamesourcefileattribute ${config.renameSourceFileAttribute.trim()}")
        }
        out.appendLine("-keepattributes SourceFile,LineNumberTable,Signature,InnerClasses,EnclosingMethod,Exceptions")
        out.appendLine("-keepattributes RuntimeVisibleAnnotations,RuntimeVisibleParameterAnnotations,AnnotationDefault")
        if (config.stripKotlinMetadata) {
            out.appendLine()
            out.appendLine("# Strip @kotlin.Metadata annotations when kotlin-reflect is unused at runtime.")
            out.appendLine("-assumenosideeffects class kotlin.Metadata { *; }")
        }
    }

    private fun appendSharedKeepRules(out: StringBuilder, config: ProGuardRuleConfig, androidSignatures: Boolean) {
        if (config.keepKotlinxSerialization) {
            out.appendLine()
            out.appendLine("# Keep kotlinx.serialization Companion and serializer() lookups without pinning class names.")
            out.appendLine("-if @kotlinx.serialization.Serializable class **")
            out.appendLine("-keepclassmembers class <1> {")
            out.appendLine("    static <1>\$Companion Companion;")
            out.appendLine("}")
            out.appendLine("-if @kotlinx.serialization.Serializable class ** {")
            out.appendLine("    static **\$* *;")
            out.appendLine("}")
            out.appendLine("-keepclassmembers class <2>\$<3> {")
            out.appendLine("    kotlinx.serialization.KSerializer serializer(...);")
            out.appendLine("}")
            out.appendLine("-if @kotlinx.serialization.Serializable class ** {")
            out.appendLine("    public static ** INSTANCE;")
            out.appendLine("}")
            out.appendLine("-keepclassmembers class <1> {")
            out.appendLine("    public static <1> INSTANCE;")
            out.appendLine("    kotlinx.serialization.KSerializer serializer(...);")
            out.appendLine("}")
        }
        if (config.keepEnums) {
            out.appendLine()
            out.appendLine("# Keep enum values() and valueOf() for reflection and serialization lookups.")
            out.appendLine("-keepclassmembers enum * {")
            out.appendLine("    public static **[] values();")
            out.appendLine("    public static ** valueOf(java.lang.String);")
            out.appendLine("}")
        }
        if (config.stripKotlinIntrinsics) {
            out.appendLine()
            out.appendLine("# Strip Kotlin null-check parameter-name strings.")
            out.appendLine("-assumenosideeffects class kotlin.jvm.internal.Intrinsics {")
            if (androidSignatures) {
                out.appendLine("    public static void checkNotNullParameter(java.lang.Object, java.lang.String);")
                out.appendLine("    public static void checkNotNullExpressionValue(java.lang.Object, java.lang.String);")
                out.appendLine("    public static void checkParameterIsNotNull(java.lang.Object, java.lang.String);")
                out.appendLine("    public static void checkExpressionValueIsNotNull(java.lang.Object, java.lang.String);")
                out.appendLine("    public static void checkReturnedValueIsNotNull(java.lang.Object, java.lang.String);")
                out.appendLine("    public static void checkFieldIsNotNull(java.lang.Object, java.lang.String, java.lang.String);")
            } else {
                out.appendLine("    public static void checkNotNullParameter(...);")
                out.appendLine("    public static void checkNotNullExpressionValue(...);")
                out.appendLine("    public static void checkParameterIsNotNull(...);")
                out.appendLine("    public static void checkExpressionValueIsNotNull(...);")
                out.appendLine("    public static void checkReturnedValueIsNotNull(...);")
                out.appendLine("    public static void checkFieldIsNotNull(...);")
            }
            out.appendLine("}")
        }
    }

    private fun appendExtraRules(out: StringBuilder, lines: List<String>) {
        val nonBlank = lines.map(String::trim).filter(String::isNotEmpty)
        if (nonBlank.isEmpty()) return
        out.appendLine()
        out.appendLine("# Project-specific rules.")
        for (line in nonBlank) out.appendLine(line)
    }
}
