/**
 * Top-level Gradle DSL extension (`releaseGuard { ... }`) registered by `com.awakekt.release-guard`.
 */
@Suppress("TooManyFunctions")
public abstract class ReleaseGuardExtension @Inject constructor(objects: ObjectFactory) {
    public val projectPackages: ListProperty<String> = objects.listProperty(String::class.java)
    public val projectKeywords: ListProperty<String> = objects.listProperty(String::class.java)
    public val minScore: Property<Int> = objects.property(Int::class.java)
    public val failOnSeverity: Property<String> = objects.property(String::class.java)
    public val disabledChecks: SetProperty<String> = objects.setProperty(String::class.java)
    public val severityOverrides: MapProperty<String, String> = objects.mapProperty(String::class.java, String::class.java)
    public val weightOverrides: MapProperty<String, Int> = objects.mapProperty(String::class.java, Int::class.java)
    public val allowedLibraryPathPatterns: ListProperty<String> = objects.listProperty(String::class.java)

    @get:Nested
    public val rules: ReleaseGuardRulesSpec = objects.newInstance(ReleaseGuardRulesSpec::class.java)

    @get:Nested
    public val desktop: DesktopGuardSpec = objects.newInstance(DesktopGuardSpec::class.java)

    @get:Nested
    public val web: WebGuardSpec = objects.newInstance(WebGuardSpec::class.java)

    @get:Nested
    public val android: AndroidGuardSpec = objects.newInstance(AndroidGuardSpec::class.java)

    @get:Nested
    public val ios: IosGuardSpec = objects.newInstance(IosGuardSpec::class.java)

    @get:Nested
    public val tls: TlsGuardSpec = objects.newInstance(TlsGuardSpec::class.java)

    @get:Nested
    public val secrets: SecretGuardSpec = objects.newInstance(SecretGuardSpec::class.java)

    @get:Nested
    public val assetEncryption: AssetEncryptionGuardSpec = objects.newInstance(AssetEncryptionGuardSpec::class.java)

    @get:Nested
    public val assets: AssetSecurityGuardSpec = objects.newInstance(AssetSecurityGuardSpec::class.java)

    @get:Nested
    public val shaders: ShaderSecurityGuardSpec = objects.newInstance(ShaderSecurityGuardSpec::class.java)

    @get:Nested
    public val customChecks: CustomChecksGuardSpec = objects.newInstance(CustomChecksGuardSpec::class.java)

    @get:Nested
    public val supplyChain: SupplyChainGuardSpec = objects.newInstance(SupplyChainGuardSpec::class.java)

    @get:Nested
    public val reports: ReportsGuardSpec = objects.newInstance(ReportsGuardSpec::class.java)

    public fun rules(action: Action<in ReleaseGuardRulesSpec>): Unit = action.execute(rules)
    public fun desktop(action: Action<in DesktopGuardSpec>): Unit = action.execute(desktop)
    public fun web(action: Action<in WebGuardSpec>): Unit = action.execute(web)
    public fun android(action: Action<in AndroidGuardSpec>): Unit = action.execute(android)
    public fun ios(action: Action<in IosGuardSpec>): Unit = action.execute(ios)
    public fun tls(action: Action<in TlsGuardSpec>): Unit = action.execute(tls)
    public fun secrets(action: Action<in SecretGuardSpec>): Unit = action.execute(secrets)
    public fun assetEncryption(action: Action<in AssetEncryptionGuardSpec>): Unit = action.execute(assetEncryption)
    public fun assets(action: Action<in AssetSecurityGuardSpec>): Unit = action.execute(assets)
    public fun shaders(action: Action<in ShaderSecurityGuardSpec>): Unit = action.execute(shaders)
    public fun customChecks(action: Action<in CustomChecksGuardSpec>): Unit = action.execute(customChecks)
    public fun supplyChain(action: Action<in SupplyChainGuardSpec>): Unit = action.execute(supplyChain)
    public fun reports(action: Action<in ReportsGuardSpec>): Unit = action.execute(reports)
}
