/** Configuration for curated ProGuard/R8 rules generated by `generateReleaseGuardRules`. */
public abstract class ReleaseGuardRulesSpec @Inject constructor(objects: ObjectFactory) {
    /** Desktop application entry-point class whose `main(String[])` is kept. */
    public val mainClass: Property<String> = objects.property(String::class.java)

    /** Package target passed to `-repackageclasses` (empty string flattens into the default package). */
    public val repackageClasses: Property<String> = objects.property(String::class.java)

    /** Enables `-allowaccessmodification`. */
    public val allowAccessModification: Property<Boolean> = objects.property(Boolean::class.java)

    /** Enables `-overloadaggressively`. */
    public val overloadAggressively: Property<Boolean> = objects.property(Boolean::class.java)

    /** Value passed to `-renamesourcefileattribute` (blank disables renaming). */
    public val renameSourceFileAttribute: Property<String> = objects.property(String::class.java)

    /** Strips Kotlin `Intrinsics` null-check parameter-name strings via `-assumenosideeffects`. */
    public val stripKotlinIntrinsics: Property<Boolean> = objects.property(Boolean::class.java)

    /** Strips `@kotlin.Metadata` when `kotlin-reflect` is not needed at runtime. */
    public val stripKotlinMetadata: Property<Boolean> = objects.property(Boolean::class.java)

    /** Strips `android.util.Log.v` and `Log.d` calls in Android release builds. */
    public val stripAndroidLogs: Property<Boolean> = objects.property(Boolean::class.java)

    /** Emits `kotlinx.serialization` companion/serializer keep rules without pinning class names. */
    public val keepKotlinxSerialization: Property<Boolean> = objects.property(Boolean::class.java)

    /** Keeps enum `values()` and `valueOf(String)`. */
    public val keepEnums: Property<Boolean> = objects.property(Boolean::class.java)

    /** Keeps `com.sun.jna.Library` interfaces for native symbol binding on Desktop JVM. */
    public val keepJnaLibraries: Property<Boolean> = objects.property(Boolean::class.java)

    /** Prevents R8 horizontal class merging from folding Compose `ModifierNodeElement` subclasses together. */
    public val keepComposeModifiers: Property<Boolean> = objects.property(Boolean::class.java)

    /** Emits `-dontoptimize` in Desktop ProGuard rules to prevent JVM stack-map `VerifyError` rewrites. */
    public val desktopDontOptimize: Property<Boolean> = objects.property(Boolean::class.java)

    /** Additional raw ProGuard/R8 lines appended to both desktop and Android rule files. */
    public val extraRules: ListProperty<String> = objects.listProperty(String::class.java)

    /** Additional raw ProGuard lines appended only to desktop rules. */
    public val extraDesktopRules: ListProperty<String> = objects.listProperty(String::class.java)

    /** Additional raw R8 lines appended only to Android rules. */
    public val extraAndroidRules: ListProperty<String> = objects.listProperty(String::class.java)
}

